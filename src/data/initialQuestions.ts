// Función para barajar preguntas aleatoriamente (Algoritmo Fisher-Yates)
export function getShuffledQuestions(pool: TriviaQuestion[] = INITIAL_QUESTIONS): TriviaQuestion[] {
  const shuffled = pool.map((q, idx) => ({
    ...q,
    id: `q_${idx}_${Date.now()}`,
    options: q.options.map((opt) => ({ ...opt, votes: 0 })),
  }));

  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled;
}

